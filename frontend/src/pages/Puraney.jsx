const SvgEditorPage = () => {
  const [selectedColor, setSelectedColor] = useState("#000000");
  const [activeElement, setActiveElement] = useState(null);
  const svgRef = useRef(null);

  const handleColorChange = (color) => {
    if (activeElement) {
      activeElement.setAttribute("fill", color.hex);
      setSelectedColor(color.hex);
    }
  };

  const handleElementClick = (e) => {
    if (["path", "rect", "circle", "polygon"].includes(e.target.tagName)) {
      if (activeElement) activeElement.setAttribute("stroke", "none");

      setActiveElement(e.target);
      e.target.setAttribute("stroke", "black");
      e.target.setAttribute("stroke-width", "3");

      setSelectedColor(e.target.getAttribute("fill") || "#000000");
    }
  };

  const handleExport = () => {
    // remove the border
    if (activeElement) {
      activeElement.setAttribute("stroke", "black");
      activeElement.setAttribute("stroke-width", "0");
    }

    if (svgRef.current) {
      toPng(svgRef.current).then((dataUrl) => {
        const link = document.createElement("a");
        link.href = dataUrl;
        link.download = "edited-svg.png";
        link.click();
      });
    }
  };

  return (
    <div className="flex flex-col justify-between min-h-screen bg-c6 text-center">
      <Navbar />
      <main className="flex flex-col  mt-10">
        <h1 className="text-2xl font-bold mb-5">आफ्नै पुराने बानऔँ।</h1>
        <div className="flex flex-col-reverse lg:flex-row-reverse  lg:justify-center content-center gap-5">
          <div className="flex-shrink gap-6 p-4">
            <div className="items-center gap-4">
              <ColorPicker
                selectedColor={selectedColor}
                onColorChange={handleColorChange}
              />
              <ExportButton onExport={handleExport} />
            </div>
          </div>
          <div className="m-2 lg:w-1/3">
            <SvgCanvas onElementClick={handleElementClick} svgRef={svgRef} />
          </div>
          <div className="font-serif lg:w-1/5 p-5">
            Art forms found in Dura communities. It is crafted on the walls and
            the colors used are produced from the local plants.
          </div>
        </div>
      </main>
      <Footer />
    </div>
  );
};

export default SvgEditorPage;
